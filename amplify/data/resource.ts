
import {
  a,
  defineData,
  type ClientSchema,
} from '@aws-amplify/backend';

import { pythonTemplate } from '../functions/python-template/resource';
import { discover } from '../functions/discover/resource';
import { stats } from '../functions/stats/resource';
import { notifications } from '../functions/notifications/resource';

const schema = a.schema({

  // Student profiles
  UserProfile: a.model({
    displayName: a.string().required(),
    major: a.string(),
    graduationYear: a.integer(),
    interests: a.string().array(),
    bio: a.string(),
    owner: a.string().authorization(allow => [
      allow.owner().to(['read', 'delete'])
    ]),
  })
  .authorization(allow => [
    allow.owner()
  ]),

  // Student organizations
  Club: a.model({
    name: a.string().required(),
    description: a.string(),
    category: a.string(),
    website: a.url(),
    meetingLocation: a.string(),
    foundedYear: a.integer(),
  })
  .authorization(allow => [
    allow.authenticated().to(['read']),
    allow.group('ADMINS')
  ]),

  // Student-club memberships
  Membership: a.model({
    clubId: a.id().required(),
  })
  .secondaryIndexes(index => [
    index('clubId')
  ])
  .authorization(allow => [
    allow.owner().to(['create', 'read', 'delete']),
    allow.group('ADMINS').to(['read', 'delete'])
  ]),

  // Club events
  Event: a.model({
    clubId: a.id().required(),
    title: a.string().required(),
    description: a.string(),
    startsAt: a.datetime().required(),
    endsAt: a.datetime(),
    location: a.string(),
    capacity: a.integer(),
    tags: a.string().array(), // e.g. "Finance", "Workshop"; used by Discover ranking
    status: a.enum(['scheduled', 'cancelled']).default('scheduled'),
  })
  .secondaryIndexes(index => [
    index('clubId').sortKeys(['startsAt'])
  ])
  .authorization(allow => [
    allow.authenticated().to(['read']),
    allow.group('ADMINS')
  ]),

  // Event registrations
  RSVP: a.model({
    eventId: a.id().required(),
  })
  .secondaryIndexes(index => [
    index('eventId')
  ])
  .authorization(allow => [
    allow.owner().to(['create', 'read', 'delete']),
    allow.group('ADMINS').to(['read', 'delete'])
  ]),

  // Club announcements
  Announcement: a.model({
    clubId: a.id().required(),
    title: a.string().required(),
    body: a.string().required(),
    publishedAt: a.datetime(),
  })
  .secondaryIndexes(index => [
    index('clubId')
  ])
  .authorization(allow => [
    allow.authenticated().to(['read']),
    allow.group('ADMINS')
  ]),

  // Per-student alerts generated by the Notifications Lambda. The explicit
  // userId index keeps each student's list newest-first; owner auth keeps the
  // records private even if a caller guesses another user's IDs.
  Notification: a.model({
    userId: a.string().required(),
    kind: a.enum(['announcement', 'event', 'event_updated', 'event_cancelled', 'event_reminder']).required(),
    title: a.string().required(),
    body: a.string().required(),
    clubId: a.id().required(),
    clubName: a.string(),
    resourceId: a.id().required(),
    target: a.string().required(),
    occurredAt: a.datetime().required(),
    readAt: a.datetime(),
    inApp: a.boolean().default(true),
    emailStatus: a.enum(['pending', 'sent', 'failed']),
    emailAttempts: a.integer().default(0),
  })
  .secondaryIndexes(index => [
    index('userId').sortKeys(['occurredAt']).name('byUser').queryField('listNotificationsByUser'),
    index('emailStatus').sortKeys(['occurredAt']).name('byEmailStatus').queryField('listNotificationEmailsByStatus'),
  ])
  .authorization(allow => [
    allow.ownerDefinedIn('userId').to(['read']),
  ]),

  // One preferences record per Cognito user. Email is kept here so scheduled
  // email delivery does not need broad Cognito directory access.
  NotificationPreference: a.model({
    userId: a.string().required(),
    email: a.email().required(),
    inAppAnnouncements: a.boolean().default(true),
    inAppEvents: a.boolean().default(true),
    inAppReminders: a.boolean().default(true),
    emailAnnouncements: a.boolean().default(false),
    emailEvents: a.boolean().default(false),
    emailReminders: a.boolean().default(false),
    weeklyDigest: a.boolean().default(false),
    browserAlerts: a.boolean().default(false),
    lastDigestAt: a.datetime(),
  })
  .identifier(['userId'])
  .authorization(allow => [
    allow.ownerDefinedIn('userId').to(['create', 'read', 'update']),
  ]),

  // Data structure returned by Python Lambda
  ClubSummary: a.customType({
    id: a.id().required(),
    name: a.string().required(),
    description: a.string(),
  }),

  // ---------------------------------------------------------------
  // Counts
  // Students can only read their own Membership/RSVP records, so the
  // read-only `stats` Lambda counts them. Each returns one row per id.
  // ---------------------------------------------------------------

  CountResult: a.customType({
    id: a.id().required(),
    count: a.integer().required(),
  }),

  clubMemberCounts: a.query()
    .arguments({
      clubIds: a.id().required().array().required(),
    })
    .returns(a.ref('CountResult').array())
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(stats)),

  eventRsvpCounts: a.query()
    .arguments({
      eventIds: a.id().required().array().required(),
    })
    .returns(a.ref('CountResult').array())
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(stats)),

  // AppSync query connected to Python Lambda
  getClubFromPython: a.query()
    .arguments({
      clubId: a.id().required(),
    })
    .returns(a.ref('ClubSummary'))
    .authorization(allow => [
      allow.authenticated()
    ])
    .handler(a.handler.function(pythonTemplate)),

  // ---------------------------------------------------------------
  // Discover feed
  // Posts, likes, and posting roles. Only the `discover` Lambda writes
  // these (it checks permissions); ADMINS can also manage them directly.
  // ---------------------------------------------------------------

  // Who can post for a club. ADMINS assign leaders; leaders assign posters.
  // userId is the Cognito user's sub.
  ClubRole: a.model({
    clubId: a.id().required(),
    userId: a.string().required(),
    role: a.enum(['leader', 'poster']),
  })
  .identifier(['clubId', 'userId'])
  .secondaryIndexes(index => [
    index('userId').name('byUser'),
  ])
  .authorization(allow => [
    allow.authenticated().to(['read']),
    allow.group('ADMINS'),
  ]),

  // Club posts: text and up to 4 images (S3 keys under post-images/).
  // feed is always "ALL" so the whole feed can be read newest-first from one index.
  Post: a.model({
    clubId: a.id().required(),
    authorId: a.string().required(),
    authorName: a.string(),
    body: a.string(),
    imageKeys: a.string().array(),
    likeCount: a.integer().default(0),
    postedAt: a.datetime().required(),
    editedAt: a.datetime(),
    feed: a.string().required(),
  })
  .secondaryIndexes(index => [
    index('clubId').sortKeys(['postedAt']).name('byClub').queryField('listPostsByClub'),
    index('feed').sortKeys(['postedAt']).name('byFeed').queryField('listPostsInFeed'),
  ])
  .authorization(allow => [
    allow.authenticated().to(['read']),
    allow.group('ADMINS'),
  ]),

  // One record per user per liked post.
  PostLike: a.model({
    postId: a.id().required(),
    userId: a.string().required(),
  })
  .identifier(['postId', 'userId'])
  .secondaryIndexes(index => [
    index('userId').name('byUser'),
  ])
  .authorization(allow => [
    allow.authenticated().to(['read']),
    allow.group('ADMINS'),
  ]),

  // Custom operation names must not match the ones Amplify generates for
  // each model (createPost, updatePost, deletePost, ...), or deploy fails.

  LikeResult: a.customType({
    postId: a.id().required(),
    liked: a.boolean().required(),
    likeCount: a.integer().required(),
  }),

  ClubMemberInfo: a.customType({
    userId: a.string().required(),
    name: a.string().required(),
    role: a.string(), // "leader", "poster", or null for regular members
  }),

  publishPost: a.mutation()
    .arguments({
      clubId: a.id().required(),
      body: a.string(),
      imageKeys: a.string().array(),
    })
    .returns(a.ref('Post'))
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(discover)),

  editPost: a.mutation()
    .arguments({
      postId: a.id().required(),
      body: a.string(),
    })
    .returns(a.ref('Post'))
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(discover)),

  removePost: a.mutation()
    .arguments({
      postId: a.id().required(),
    })
    .returns(a.id())
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(discover)),

  toggleLike: a.mutation()
    .arguments({
      postId: a.id().required(),
    })
    .returns(a.ref('LikeResult'))
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(discover)),

  setPostingAccess: a.mutation()
    .arguments({
      clubId: a.id().required(),
      userId: a.string().required(),
      canPost: a.boolean().required(),
    })
    .returns(a.boolean())
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(discover)),

  listClubMembers: a.query()
    .arguments({
      clubId: a.id().required(),
    })
    .returns(a.ref('ClubMemberInfo').array())
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(discover)),

  // Read state is changed through a Lambda so users can't alter notification
  // contents or reassign a notification to a different account.
  setNotificationRead: a.mutation()
    .arguments({ notificationId: a.id().required(), isRead: a.boolean().required() })
    .returns(a.boolean())
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(notifications)),

  markAllNotificationsRead: a.mutation()
    .returns(a.boolean())
    .authorization(allow => [allow.authenticated()])
    .handler(a.handler.function(notifications)),

});

export type Schema = ClientSchema<typeof schema>;

export const data = defineData({
  schema,
  authorizationModes: {
    defaultAuthorizationMode: 'userPool',
  },
});
